"""Write base/eb22.yaml from eb21.yaml: eb21 warm start + the two positive A/Bs, rolesym and corefC (option A, 2026-10-19).

rolesym-treatment's data and flag (exact eb21 replay without casie/rams_merged/wikievents + those three in full,
`negative_gold_full_roles: true`) plus corefC-treatment's LLM news coref and link (weight 0.3, 4 negatives).
`replay_eb21_coref34` is left out: it draws from the same eb21 mixture and duplicates 3,499 of rolesym's replay
records exactly. GUM/LitBank/GAP stay out (user, aab28b3). Eval: eb21's own val/test files + app:news55.
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
d = src["data"]
skip = set(d["train_only"])
ev = {}
for c in d["corpora"]:
    name = Path(c).name
    if name in skip:
        continue
    split = {s: f"{c}.{s}.jsonl" for s in ("val", "test")
             if Path(f"{c}.{s}.jsonl").is_file() and Path(f"{c}.{s}.jsonl").stat().st_size}
    if split:
        ev[name if name not in d["event_files"] else f"{name}_full"] = split
for name, v in d["event_files"].items():
    split = {s: v[s] for s in ("val", "test") if s in v}
    if split:
        ev[name] = split
TRAIN = ["replay_eb21_rolesym", "casie", "rams_merged", "wikievents",
         "cc_news_events_sonnet55_v2_coref_llm", "cc_news_events_haiku45_coref_llm", "cc_news_haiku45_coref_llm",
         "wikievents_coref_llm"]
bh = dict(src["model"]["boundary_head"], entity_coref_link=True, entity_coref_link_weight=0.3, entity_coref_link_negatives=4)
cfg = {
    "model": {"pretrained": "whr778/gliner2-eb21", "architecture": "boundary", "max_len": 8192,
              "attn_implementation": "flash_attention_2", "boundary_head": bh},
    "training": dict(src["training"], negative_pools="tools/train/config/pools/eb21.negative_pools.json",
                     negative_gold_full_roles=True,
                     output_dir="./out/eb22", experiment_name="eb22", num_epochs=2,
                     encoder_lr=1.0e-5, task_lr=1.0e-4, warmup_ratio=0.1, scheduler_type="cosine", save_total_limit=2),
    "eval": {k: v for k, v in src["eval"].items() if k not in ("coref_calibration", "coref_control")}
            | {"threshold_sweep": False, "app_menus": {"news55": "../menus/news55.json"}},
    "labels_file": "../" + src["labels_file"],
    "data": {"corpora": [f"data/{c}" for c in TRAIN], "train_only": TRAIN,
             "partial_annotation": d["partial_annotation"], "event_files": ev},
}
head = ("# eb22 -- GENERATED by tools/train/make_eb22_config.py from base/eb21.yaml; edit that, not this.\n"
        "# Warm start eb21, 2 epochs = rolesym-treatment + corefC-treatment combined. TRAIN: exact eb21 replay without\n"
        "# casie/rams_merged/wikievents (replay_eb21_rolesym) + those three in full + LLM news coref (*_coref_llm).\n"
        "# FLAGS: negative_gold_full_roles true; entity_coref_link weight 0.3. EVAL: eb21's own val/test + app:news55.\n")
Path("tools/train/config/base/eb22.yaml").write_text(
    head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
print("train", TRAIN, "| eval entries", len(ev))
