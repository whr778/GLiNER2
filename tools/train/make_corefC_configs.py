"""Write the corefC arm configs (bought LLM news coref, 34% replay) from eb21.yaml: train on replay + English coref, evaluate on eb21's exact val/test."""
import sys, yaml
from pathlib import Path
src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
d = src["data"]
skip = set(d["train_only"])
ev = {}
for c in d["corpora"]:
    name = Path(c).name
    if name in skip:
        continue
    split = {s: f"{c}.{s}.jsonl" for s in ("val", "test") if Path(f"{c}.{s}.jsonl").is_file() and Path(f"{c}.{s}.jsonl").stat().st_size}
    if split:
        ev[name if name not in d["event_files"] else f"{name}_full"] = split
for name, v in d["event_files"].items():
    split = {s: v[s] for s in ("val", "test") if s in v}
    if split:
        ev[name] = split
LLM = ["cc_news_events_sonnet55_v2_coref_llm", "cc_news_events_haiku45_coref_llm", "cc_news_haiku45_coref_llm",
       "wikievents_coref_llm"]
FREE = ["gum_coref", "litbank_coref", "gap_coref"]
ARMS = {"control": (0.0, "replay_eb21_coref34", LLM), "treatment": (0.3, "replay_eb21_coref34", LLM),
        "treatment-free": (0.3, "replay_eb21_coref34free", LLM + FREE)}
for arm, (weight, replay, new) in ARMS.items():
    bh = dict(src["model"]["boundary_head"], entity_coref_link=True, entity_coref_link_weight=weight, entity_coref_link_negatives=4)
    train = [replay] + new
    cfg = {
        "model": {"pretrained": "whr778/gliner2-eb21", "architecture": "boundary", "max_len": 8192,
                  "attn_implementation": "flash_attention_2", "boundary_head": bh},
        "training": dict(src["training"], negative_pools="tools/train/config/pools/eb21.negative_pools.json",
                         output_dir=f"./out/corefC-{arm}", experiment_name=f"corefC_{arm}", num_epochs=2,
                         encoder_lr=1.0e-5, task_lr=1.0e-4, warmup_ratio=0.1, scheduler_type="cosine", save_total_limit=2),
        "eval": {k: v for k, v in src["eval"].items() if k not in ("coref_calibration", "app_menus", "menu", "coref_control")}
                | {"threshold_sweep": False},
        "labels_file": "../" + src["labels_file"],
        "data": {"corpora": [f"data/{c}" for c in train], "train_only": train,
                 "partial_annotation": d["partial_annotation"], "event_files": ev},
    }
    head = (f"# corefC ({arm}) -- GENERATED by tools/train/make_corefC_configs.py from base/eb21.yaml; edit that, not this.\n"
            f"# Warm start eb21. TRAIN: 34% exact eb21 replay ({replay}) + LLM news coref (Sonnet 5.5, *_coref_llm)"
            f"{' + GUM/LitBank/GAP' if FREE[0] in new else ''}.\n"
            f"# EVAL: eb21's own val/test files, unchanged. control vs treatment: ONLY entity_coref_link_weight\n"
            f"# ({weight} here). treatment vs treatment-free: ONLY GUM/LitBank/GAP (+ the replay records that keep 34%;\n"
            f"# replay_eb21_coref34free is a strict superset of replay_eb21_coref34).\n")
    Path(f"tools/train/config/ab/corefC-{arm}.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(arm, "weight", weight, "train", train, "eval entries", len(ev))
