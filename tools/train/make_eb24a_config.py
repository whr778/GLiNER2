"""Write base/eb24a.yaml from base/eb23a.yaml.

eb23a with ONE training change:
- training.expand_argument_coref: false — stops copying full-document `coref_clusters`
  mentions and pronouns onto event role targets (which polluted the 11,534
  `sonnet55_v2` / `haiku45` / `wikievents_off` event records in eb23a and collapsed
  single-corpus ACE/WikiEvents `event_argument` F1), while `MentionLink`
  (`entity_coref_loss`) continues training on 100% of `coref_clusters` via
  `coref.attach`.

All 27 corpora, val/test splits (19,286 / 20,602), `labels/unified-full-v4.yaml`,
and boundary-head / optimizer settings stay identical to eb23a so the comparison is
unconfounded.

    uv run python tools/train/make_eb24a_config.py
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb23a.yaml", encoding="utf-8"))
head = src["model"]["boundary_head"]
assert src["model"]["strip_bare_space_subword"] is True
assert head["pair_split_reduction"] is True
assert head["hard_negative_keep_all_when_absent"] is False
assert head["record_drop_anchor_field_loss"] is True
assert head["record_field_max_tokens"] == 48
assert head["entity_coref_threshold"] == 0.5
assert "expand_argument_coref" not in src["training"]

cfg = dict(src)
cfg["training"] = dict(
    src["training"],
    output_dir="./out/eb24a",
    experiment_name="eb24a",
    expand_argument_coref=False,
)
note = (
    "# eb24a -- GENERATED by tools/train/make_eb24a_config.py from base/eb23a.yaml; edit that, not this.\n"
    "# eb23a with ONE training change: expand_argument_coref: false (keeps event role targets local while\n"
    "# MentionLink continues training on 100% of coref_clusters).\n"
)
Path("tools/train/config/base/eb24a.yaml").write_text(
    note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8",
)
print("wrote tools/train/config/base/eb24a.yaml")
