"""Write the relneg A/B arm configs from eb21.yaml: do relation negatives help or hurt relations? (2026-10-19)

Warm start eb21, 2 epochs, both arms on the SAME data: professorbob_re in full (13,926; in eb21's mix and in the
negative pools, 197 relation types) + an exact eb21 replay (replay_eb21_coref34, 13,990; 805 of its records are
professorbob_re records, so they appear twice -- identically in both arms). Eval: eb21's own val/test files.
The arms differ in ONE line: `negative_labels_per_dim.relations` (absent in control, 20 in treatment, the
entities/events dose). The read is professorbob_re VAL under its full relation menu, treatment vs control.
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
d = src["data"]
skip = set(d["train_only"])
ev = {}
for c in d["corpora"]:
    name = Path(c).name
    if name in skip:
        continue
    split = {s: f"{c}.{s}.jsonl" for s in ("val", "test")
             if Path(f"{c}.{s}.jsonl").is_file() and Path(f"{c}.{s}.jsonl").stat().st_size}
    if split:
        ev[name if name not in d["event_files"] else f"{name}_full"] = split
for name, v in d["event_files"].items():
    split = {s: v[s] for s in ("val", "test") if s in v}
    if split:
        ev[name] = split
TRAIN = ["replay_eb21_coref34", "professorbob_re"]
for arm, rel_dose in (("control", None), ("treatment", 20)):
    per_dim = dict(src["training"]["negative_labels_per_dim"])
    if rel_dose:
        per_dim["relations"] = rel_dose
    cfg = {
        "model": {"pretrained": "whr778/gliner2-eb21", "architecture": "boundary", "max_len": 8192,
                  "attn_implementation": "flash_attention_2", "boundary_head": src["model"]["boundary_head"]},
        "training": dict(src["training"], negative_pools="tools/train/config/pools/eb21.negative_pools.json",
                         negative_labels_per_dim=per_dim,
                         output_dir=f"./out/relneg-{arm}", experiment_name=f"relneg_{arm}", num_epochs=2,
                         encoder_lr=1.0e-5, task_lr=1.0e-4, warmup_ratio=0.1, scheduler_type="cosine", save_total_limit=2),
        "eval": {k: v for k, v in src["eval"].items() if k not in ("coref_calibration", "app_menus", "menu", "coref_control")}
                | {"threshold_sweep": False},
        "labels_file": "../" + src["labels_file"],
        "data": {"corpora": [f"data/{c}" for c in TRAIN], "train_only": TRAIN,
                 "partial_annotation": d["partial_annotation"], "event_files": ev},
    }
    head = (f"# relneg ({arm}) -- GENERATED by tools/train/make_relneg_configs.py from base/eb21.yaml; edit that, not this.\n"
            "# Warm start eb21. TRAIN: exact eb21 replay (replay_eb21_coref34) + professorbob_re in full. EVAL: eb21's own\n"
            f"# val/test files. control vs treatment: ONLY negative_labels_per_dim.relations ({rel_dose or 'absent'} here).\n")
    Path(f"tools/train/config/ab/relneg-{arm}.yaml").write_text(
        head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(arm, "negatives", per_dim, "| train", TRAIN, "| eval entries", len(ev))
