"""Write base/eb22b.yaml: eb22 as OPTION B -- eb21's from-scratch recipe plus everything learned since (2026-10-19).

Relations were never fitted in eb21 (TODO #40) and `relation_biaffine_content` is structural, so this base is
built from the encoder, not warm-started. On top of eb21.yaml:

  STRUCTURAL, from fastino/gliner2.5-multi-v1 (user):
    relation scorer      relation_biaffine_content, directional_relation_states
    span representation  enable_span_content, enable_rotary_endpoints, endpoint_difference_features,
                         query_conditioned_inside_weight
    boundary attention   boundary_attention_layers 2, boundary_attention_window 128
  NON-STRUCTURAL, from fastino (user): asymmetric focal boundary loss, negative weight 0.5, top-k alpha 0.08,
    hard negatives 20 per positive (min 16, keep all when absent), negative query ratio 1.0;
    relation pair cap 64, relation argument proposal threshold 0.2.
  KEPT AS OURS (user): mmBERT, eb21's proposal budgets, candidate_pool per_query (the shared-pool attention
    layers never run under per_query), loss_reduction global -- fastino's `sum` grows the span terms with document
    length (pair 42,053 vs relation 0.69 on one traced batch) and would starve the mean-reduced relation, coref,
    classification and record losses further.
  PROVEN SINCE eb21: negative_gold_full_roles (rolesym), entity_coref_link 0.3 on the LLM news coref (corefC),
    relation_gold_pairs nearest + labels v4 (TODO #40), coref clusters by position (590d038).
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
FASTINO_STRUCTURAL = {
    "relation_biaffine_content": True, "directional_relation_states": True,
    "enable_span_content": True, "enable_rotary_endpoints": True, "endpoint_difference_features": True,
    "query_conditioned_inside_weight": True,
    "boundary_attention_layers": 2, "boundary_attention_window": 128,
}
FASTINO_LOSS = {
    "boundary_marginal_loss": "asymmetric_focal", "boundary_negative_weight": 0.5, "boundary_top_k_alpha": 0.08,
    "hard_negatives_per_positive": 20, "minimum_hard_negatives": 16,
    "hard_negative_keep_all_when_absent": True, "negative_query_ratio": 1.0,
    "relation_pair_cap": 64, "relation_argument_proposal_threshold": 0.2,
}
COREF = {"entity_coref_link": True, "entity_coref_link_weight": 0.3, "entity_coref_link_negatives": 4}
COREF_LLM = ["cc_news_events_sonnet55_v2_coref_llm", "cc_news_events_haiku45_coref_llm", "cc_news_haiku45_coref_llm",
             "wikievents_coref_llm"]

cfg = dict(src)
cfg["model"] = dict(src["model"], boundary_head=dict(src["model"]["boundary_head"], **FASTINO_STRUCTURAL, **FASTINO_LOSS, **COREF))
cfg["training"] = dict(src["training"], negative_gold_full_roles=True, relation_gold_pairs="nearest",
                       output_dir="./out/eb22b", experiment_name="eb22b")
cfg["labels_file"] = "labels/unified-full-v4.yaml"
d = dict(src["data"])
d["corpora"] = list(d["corpora"]) + [f"data/{c}" for c in COREF_LLM]
d["train_only"] = list(d["train_only"]) + COREF_LLM
cfg["data"] = d
head = ("# eb22b -- GENERATED by tools/train/make_eb22b_config.py from base/eb21.yaml; edit that, not this.\n"
        "# eb22 as OPTION B: FROM SCRATCH (mmBERT), eb21's recipe + fastino gliner2.5-multi-v1's structural relation/span\n"
        "# flags and boundary attention + its loss/negative settings + rolesym's full roles + corefC's link and data +\n"
        "# relation_gold_pairs nearest + labels v4. Kept: eb21's budgets, per_query. See the maker's docstring.\n")
Path("tools/train/config/base/eb22b.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
print("wrote tools/train/config/base/eb22b.yaml | corpora", len(d["corpora"]), "| train_only", len(d["train_only"]))
