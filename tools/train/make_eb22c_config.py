"""Write base/eb22c.yaml: eb22b + OFFSET-ANCHORED event gold (TODO #26, 2026-10-19).

String gold marks every occurrence of a trigger or argument's text; each occurrence of an argument becomes a separate
REQUIRED value of its list role (eb21 collator, sampling off: wikievents x4.11, cc_news_events_sonnet55_v2 x2.90, casie
x2.14, cmnee_ner x1.79). Offset gold (`{text, start, end}`) marks only the annotated occurrence. The processor and
the sliding window accept it since 2026-10-19; first measured 2026-10-14 (`measure_occurrence_ambiguity.py`,
EVENT_ARGUMENT_DIAGNOSIS s4l).

Swapped (argument targets, eb21 collator, sampling off):
  wikievents -> wikievents_off   x3.48 -> x1.00   train-only
  cmnee_ner  -> cmnee_ner_off    x1.85 -> x1.00   train-only
  casie      -> casie_off        x1.87 -> x1.01   EVALUATED: casie_off ships byte-identical copies of casie.val/test
                                                  (strings -- the evaluator matches text), so evaluation is unchanged
The swap also rewrites an `event_files` entry's paths to the swapped corpus (eb22b loads casie's train and test through
event_files too; eval files are de-duplicated by NAME, so a stale casie.test.jsonl would count CASIE's test twice).
Every other line is eb22b's.
"""
import filecmp
from pathlib import Path

import yaml

OFFSET_SWAPS = {"wikievents": "wikievents_off", "cmnee_ner": "cmnee_ner_off", "casie": "casie_off"}

src = yaml.safe_load(open("tools/train/config/base/eb22b.yaml", encoding="utf-8"))
cfg = dict(src)
d = dict(src["data"])
d["corpora"] = [f"data/{OFFSET_SWAPS.get(Path(c).name, Path(c).name)}" for c in d["corpora"]]
d["train_only"] = [OFFSET_SWAPS.get(c, c) for c in d["train_only"]]
# partial_annotation is keyed by corpus name too: a stale `cmnee_ner` key made build_negative_pools refuse the config
# and killed the first eb22c launch at startup (2026-10-19).
d["partial_annotation"] = {OFFSET_SWAPS.get(c, c): dims for c, dims in d["partial_annotation"].items()}
for old, new in OFFSET_SWAPS.items():
    if old not in src["data"]["train_only"]:      # evaluated corpus: its val/test must not change with the swap
        for split in ("val", "test"):
            a, b = Path(f"data/{old}.{split}.jsonl"), Path(f"data/{new}.{split}.jsonl")
            if a.is_file():
                assert b.is_file() and filecmp.cmp(a, b, shallow=False), f"{b} must be a byte-identical copy of {a}"
ev = {}
for name, files in d["event_files"].items():
    files = dict(files)
    for old, new in OFFSET_SWAPS.items():
        for split in ("train", "val", "test"):
            # val/test too: train.py de-duplicates eval files by NAME, so a corpus entry `casie_off.test.jsonl` beside
            # an event_files `casie.test.jsonl` (identical content) counted CASIE's test twice until this rewrite.
            if files.get(split) == f"data/{old}.{split}.jsonl":
                files[split] = f"data/{new}.{split}.jsonl"
    ev[name] = files
d["event_files"] = ev
cfg["data"] = d
# 5 epochs (user, 2026-10-19): eb21 stopped at epoch 3 still rising and its relations only began to learn there; the
# LR schedule spans num_epochs, so the count belongs in the config, not only in a hand-stop.
cfg["training"] = dict(src["training"], output_dir="./out/eb22c", experiment_name="eb22c", num_epochs=5)
head = ("# eb22c -- GENERATED by tools/train/make_eb22c_config.py from base/eb22b.yaml; edit that, not this.\n"
        "# eb22b + OFFSET-ANCHORED event gold (TODO #26): event corpora's TRAIN gold swapped for {text, start, end};\n"
        f"# val/test unchanged (strings). Swaps: {OFFSET_SWAPS}. Everything else is eb22b's.\n")
Path("tools/train/config/base/eb22c.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
print("wrote tools/train/config/base/eb22c.yaml | swaps", OFFSET_SWAPS)
