"""Write base/eb22c.yaml: eb22b + OFFSET-ANCHORED event gold (TODO #26, 2026-10-19).

String gold marks every occurrence of a trigger or argument's text; each occurrence of an argument becomes a separate
REQUIRED value of its list role (eb21 collator, sampling off: wikievents x4.11, cc_news_events_sonnet55_v2 x2.90, casie
x2.14, cmnee_ner x1.79). Offset gold (`{text, start, end}`) marks only the annotated occurrence. The processor and
the sliding window accept it since 2026-10-19; first measured 2026-10-14 (`measure_occurrence_ambiguity.py`,
EVENT_ARGUMENT_DIAGNOSIS s4l).

Swapped so far (train-only corpora; their val/test stay strings, the evaluator matches text):
  wikievents -> wikievents_off   (argument targets x3.48 -> x1.00 on the same documents)
Every other line is eb22b's.
"""
from pathlib import Path

import yaml

OFFSET_SWAPS = {"wikievents": "wikievents_off"}

src = yaml.safe_load(open("tools/train/config/base/eb22b.yaml", encoding="utf-8"))
cfg = dict(src)
d = dict(src["data"])
d["corpora"] = [f"data/{OFFSET_SWAPS.get(Path(c).name, Path(c).name)}" for c in d["corpora"]]
d["train_only"] = [OFFSET_SWAPS.get(c, c) for c in d["train_only"]]
for old in OFFSET_SWAPS:
    assert old in src["data"]["train_only"], f"{old} must be train-only in eb22b: its eval files would change with it"
cfg["data"] = d
cfg["training"] = dict(src["training"], output_dir="./out/eb22c", experiment_name="eb22c")
head = ("# eb22c -- GENERATED by tools/train/make_eb22c_config.py from base/eb22b.yaml; edit that, not this.\n"
        "# eb22b + OFFSET-ANCHORED event gold (TODO #26): train-only event corpora swapped for their {text, start, end}\n"
        f"# versions: {OFFSET_SWAPS}. Everything else is eb22b's.\n")
Path("tools/train/config/base/eb22c.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
print("wrote tools/train/config/base/eb22c.yaml | swaps", OFFSET_SWAPS)
