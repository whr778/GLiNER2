"""Write the rolesym A/B arm configs from eb21.yaml: does listing full role sets on gold event types remove the poison?

Warm start eb21, 2 epochs, both arms on the SAME data: an exact eb21 replay drawn without casie / rams_merged /
wikievents (data/replay_eb21_rolesym, 29,276) plus those three in full (7,319) -- where the rarely argued role
listings are. Eval: eb21's own val/test files and its app:news55 menu, unchanged. The arms differ in ONE line,
`negative_gold_full_roles`. Read treatment vs control, not vs eb21: both arms move toward the event corpora.
"""
import yaml
from pathlib import Path

src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
d = src["data"]
skip = set(d["train_only"])
ev = {}
for c in d["corpora"]:
    name = Path(c).name
    if name in skip:
        continue
    split = {s: f"{c}.{s}.jsonl" for s in ("val", "test")
             if Path(f"{c}.{s}.jsonl").is_file() and Path(f"{c}.{s}.jsonl").stat().st_size}
    if split:
        ev[name if name not in d["event_files"] else f"{name}_full"] = split
for name, v in d["event_files"].items():
    split = {s: v[s] for s in ("val", "test") if s in v}
    if split:
        ev[name] = split
TRAIN = ["replay_eb21_rolesym", "casie", "rams_merged", "wikievents"]
for arm, full_roles in (("control", False), ("treatment", True)):
    cfg = {
        "model": {"pretrained": "whr778/gliner2-eb21", "architecture": "boundary", "max_len": 8192,
                  "attn_implementation": "flash_attention_2", "boundary_head": src["model"]["boundary_head"]},
        "training": dict(src["training"], negative_pools="tools/train/config/pools/eb21.negative_pools.json",
                         negative_gold_full_roles=full_roles,
                         output_dir=f"./out/rolesym-{arm}", experiment_name=f"rolesym_{arm}", num_epochs=2,
                         encoder_lr=1.0e-5, task_lr=1.0e-4, warmup_ratio=0.1, scheduler_type="cosine", save_total_limit=2),
        "eval": {k: v for k, v in src["eval"].items() if k not in ("coref_calibration", "coref_control")}
                | {"threshold_sweep": False, "app_menus": {"news55": "../menus/news55.json"}},
        "labels_file": "../" + src["labels_file"],
        "data": {"corpora": [f"data/{c}" for c in TRAIN], "train_only": TRAIN,
                 "partial_annotation": d["partial_annotation"], "event_files": ev},
    }
    head = (f"# rolesym ({arm}) -- GENERATED by tools/train/make_rolesym_configs.py from base/eb21.yaml; edit that, not this.\n"
            "# Warm start eb21. TRAIN: exact eb21 replay without casie/rams_merged/wikievents (replay_eb21_rolesym) + those\n"
            "# three in full. EVAL: eb21's own val/test files + app:news55, unchanged. control vs treatment: ONLY\n"
            f"# negative_gold_full_roles ({full_roles} here). PARTIAL ANNOTATION is not extended to roles: the LLM-annotated\n"
            "# cc_news corpora were annotated against the type's role menu, so an unargued role is read as absent there too.\n")
    Path(f"tools/train/config/ab/rolesym-{arm}.yaml").write_text(
        head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(arm, "full roles", full_roles, "| train", TRAIN, "| eval entries", len(ev))
