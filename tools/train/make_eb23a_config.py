"""Write base/eb23a.yaml from base/eb22g.yaml.

eb22g plus the 2026-11-09 code-review & mmBERT subword-pooling additions:
- model.strip_bare_space_subword: true (strip standalone leading '▁'/'Ġ' subword when len(subs) > 1
  so numbers ['▁', '2', '0', '2', '6'] and 19% of CJK characters ['▁', '俄'] pool at their actual
  digit/character token instead of the shared bare '▁' space token)
- boundary_head.record_field_max_tokens: 48 (caps multi-sentence chimeric arguments in forward_group
  and decode_group while covering 99.93% of CJK event arguments and 99.9994% of English event arguments)
- boundary_head.record_field_min_pair_logit: -10.0 (with doc_offset prefix-choice exemption)

    uv run tools/train/make_eb23a_config.py
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb22g.yaml", encoding="utf-8"))
head = dict(src["model"]["boundary_head"])
assert head["pair_split_reduction"] is True
assert head["hard_negative_keep_all_when_absent"] is False
assert head["record_drop_anchor_field_loss"] is True

head["record_field_max_tokens"] = 48
head["record_field_min_pair_logit"] = -10.0
head["entity_coref_threshold"] = 0.5
head["record_argument_coref_match"] = "relaxed"
head["record_argument_coref_copy"] = "canonical"
head["record_argument_coref_min_score"] = 0.25
head["record_argument_coref_boost"] = 0.0

model_block = dict(src["model"])
model_block["strip_bare_space_subword"] = True
model_block["boundary_head"] = head

cfg = dict(src)
cfg["model"] = model_block
cfg["training"] = dict(
    src["training"],
    output_dir="./out/eb23a",
    experiment_name="eb23a",
)
note = (
    "# eb23a -- GENERATED by tools/train/make_eb23a_config.py from base/eb22g.yaml; edit that, not this.\n"
    "# eb22g plus strip_bare_space_subword: true, record_field_max_tokens: 48, record_field_min_pair_logit: -10.0,\n"
    "# and in-engine entity_coref_threshold: 0.5 (relaxed match, canonical copy, min_score 0.25, boost 0.0).\n"
)
Path("tools/train/config/base/eb23a.yaml").write_text(
    note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8",
)
print("wrote tools/train/config/base/eb23a.yaml")
