"""Write eb21-trace and eb21-5ep-trace: the KNOWN-GOOD base watched at the resolution eb22c collapsed at.

eb22c's events collapse between steps ~4,000 and ~8,000 on one GPU, and BOTH round-1 bisect arms (loss knobs removed,
structural flags removed) collapse too (2026-10-20). eb21 "learned events" -- but it was only ever evaluated once per
epoch (~16,700 steps on one GPU), so a mid-epoch dip would have been invisible. Its one schedule difference: num_epochs 9
vs eb22c's 5, so warmup (5% of the run) peaks at step ~7,500 instead of ~4,200.
    eb21-trace      eb21 UNCHANGED; eval + checkpoint every 1000 steps (1500 val records), [losses]/[grads] logged
    eb21-5ep-trace  eb21 with ONE change: num_epochs 5 (eb22c's schedule)

    uv run tools/train/make_eb21_trace_configs.py
    bash tools/train/run_logged.sh tools/train/config/base/eb21-trace.yaml 1
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
assert src["training"]["num_epochs"] == 9, "eb21's schedule is the control; re-read it if this changed"
for name, change in (("eb21-trace", {}), ("eb21-5ep-trace", {"num_epochs": 5})):
    cfg = dict(src)
    cfg["training"] = dict(src["training"], output_dir=f"./out/{name}", experiment_name=name, eval_strategy="steps",
                           eval_steps=1000, max_eval_samples=1500, save_total_limit=30, **change)
    note = (f"# {name} -- GENERATED by tools/train/make_eb21_trace_configs.py from base/eb21.yaml; edit that, not this.\n"
            f"# eb21 except: eval + checkpoint every 1000 steps on 1500 val records, 30 kept; training change {change or 'none'}.\n")
    Path(f"tools/train/config/base/{name}.yaml").write_text(note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
                                                           encoding="utf-8")
    print(f"wrote tools/train/config/base/{name}.yaml | change {change or 'none'}")
