"""Write base/eb22g.yaml from base/eb22f.yaml.

eb22f plus the 2026-11-04 events-pipeline review fixes:
- pair_split_reduction: true (split candidate_pair_loss into positive mean + hard-negative mean)
- hard_negative_keep_all_when_absent: false (keep minimum_hard_negatives=16 on absent queries instead of all 768)
- schema_dropout: {remove_events_prob: 0.0} (do not drop 20% of gold event types per collate)
- grouped occurrence/coreferent alternatives in RecordFieldTarget.values (code)

    uv run tools/train/make_eb22g_config.py
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb22f.yaml", encoding="utf-8"))
head = src["model"]["boundary_head"]
assert head["record_drop_anchor_field_loss"] is True
assert head["hard_negative_keep_all_when_absent"] is True
assert "pair_split_reduction" not in head
cfg = dict(src)
cfg["model"] = dict(src["model"], boundary_head=dict(
    head,
    pair_split_reduction=True,
    hard_negative_keep_all_when_absent=False,
))
cfg["training"] = dict(
    src["training"],
    output_dir="./out/eb22g",
    experiment_name="eb22g",
    schema_dropout={"remove_events_prob": 0.0},
)
note = (
    "# eb22g -- GENERATED by tools/train/make_eb22g_config.py from base/eb22f.yaml; edit that, not this.\n"
    "# eb22f plus pair_split_reduction: true, hard_negative_keep_all_when_absent: false, and remove_events_prob: 0.0.\n"
)
Path("tools/train/config/base/eb22g.yaml").write_text(
    note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8",
)
print("wrote tools/train/config/base/eb22g.yaml")
