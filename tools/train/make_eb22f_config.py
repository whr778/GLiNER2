"""Write base/eb22f.yaml from base/eb22e.yaml.

eb22e plus the role-loss and format-gate fixes verified in overfit-events-eb22e:
- _list_field_bce splits the gold mean and hard-negative mean (code, live when record_role_hard_negatives > 0)
- _instance_field_loss withholds unresolved gold roles and masks candidates overlapping unresolved fillers (code)
- record_drop_anchor_field_loss: true drops the unread anchor self-row from the natural-mode field loss
- _format_field gates and stores the assignment probability rather than min(pair, assignment) (code)

    uv run tools/train/make_eb22f_config.py
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb22e.yaml", encoding="utf-8"))
head = src["model"]["boundary_head"]
assert head["span_residual_zero_init"] is True
assert head["enable_rotary_endpoints"] is False
assert "record_drop_anchor_field_loss" not in head
cfg = dict(src)
cfg["model"] = dict(src["model"], boundary_head=dict(
    head,
    record_drop_anchor_field_loss=True,
))
cfg["training"] = dict(src["training"], output_dir="./out/eb22f", experiment_name="eb22f")
note = (
    "# eb22f -- GENERATED by tools/train/make_eb22f_config.py from base/eb22e.yaml; edit that, not this.\n"
    "# eb22e plus record_drop_anchor_field_loss: true and the split role-loss / unresolved-role withhold / format-gate fixes.\n"
)
Path("tools/train/config/base/eb22f.yaml").write_text(
    note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8",
)
print("wrote tools/train/config/base/eb22f.yaml")
