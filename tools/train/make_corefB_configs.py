"""Write the option-B arm configs from eb21.yaml: train on replay + English coref, evaluate on eb21's exact val/test."""
import sys, yaml
from pathlib import Path
src = yaml.safe_load(open("tools/train/config/base/eb21.yaml", encoding="utf-8"))
d = src["data"]
skip = set(d["train_only"])
ev = {}
for c in d["corpora"]:
    name = Path(c).name
    if name in skip:
        continue
    split = {s: f"{c}.{s}.jsonl" for s in ("val", "test") if Path(f"{c}.{s}.jsonl").is_file() and Path(f"{c}.{s}.jsonl").stat().st_size}
    if split:
        ev[name if name not in d["event_files"] else f"{name}_full"] = split
for name, v in d["event_files"].items():
    split = {s: v[s] for s in ("val", "test") if s in v}
    if split:
        ev[name] = split
for arm, weight in (("treatment", 0.3), ("control", 0.0)):
    bh = dict(src["model"]["boundary_head"], entity_coref_link=True, entity_coref_link_weight=weight, entity_coref_link_negatives=4)
    cfg = {
        "model": {"pretrained": "whr778/gliner2-eb21", "architecture": "boundary", "max_len": 8192,
                  "attn_implementation": "flash_attention_2", "boundary_head": bh},
        "training": dict(src["training"], negative_pools="tools/train/config/pools/eb21.negative_pools.json",
                         output_dir=f"./out/corefB-{arm}", experiment_name=f"corefB_{arm}", num_epochs=4,
                         encoder_lr=1.0e-5, task_lr=1.0e-4, warmup_ratio=0.1, scheduler_type="cosine", save_total_limit=4),
        "eval": {k: v for k, v in src["eval"].items() if k not in ("coref_calibration", "app_menus", "menu", "coref_control")}
                | {"threshold_sweep": False},
        "labels_file": "../" + src["labels_file"],
        "data": {"corpora": ["data/replay_eb21_coref30", "data/wikievents", "data/gum_coref", "data/litbank_coref", "data/gap_coref"],
                 "train_only": ["replay_eb21_coref30", "wikievents", "gum_coref", "litbank_coref", "gap_coref"],
                 "partial_annotation": d["partial_annotation"], "event_files": ev},
    }
    head = (f"# Option B ({arm}), coref plan step 3 -- GENERATED by tools/train/make_corefB_configs.py from base/eb21.yaml; edit that, not this.\n"
            f"# Warm start eb21 (epoch 3). TRAIN: 30% exact eb21 replay (source-tagged) + WikiEvents + GUM/LitBank/GAP\n"
            f"# coref. EVAL: eb21's own val/test files, unchanged, so forgetting is read against the control.\n"
            f"# The ONLY arm difference: entity_coref_link_weight {weight} (link built in both; 0 == off, traced).\n"
            f"# Negatives: eb21's pools (pools/eb21.negative_pools.json); coref-only corpora get none on purpose.\n")
    Path(f"tools/train/config/ab/corefB-{arm}.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(arm, "eval entries", len(ev))
