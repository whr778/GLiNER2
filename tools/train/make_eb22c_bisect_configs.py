# Geometry / distance arms (2026-10-22). Measured on the 30k control: the junction's geometry channel is 86-92% of the
# junction term and carries the English column discrimination (CASIE 0.853 -> 0.709 without it), but with no activation
# it is rank-2 in (order, log distance) -- a GELU makes it a per-role MLP over the two features (width then matters).
