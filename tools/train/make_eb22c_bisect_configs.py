# 0.944, CMNEE 0.743 -> 0.814): one monotone slope is wrong often enough; an MLP distance channel can learn the shape or
# switch itself off. ONE functional change each against eb22c-ddp-trace (both terms are 0 at init; RNG parity keeps every
# other weight bit-identical at init); save_epoch_checkpoint for a clean restart.
