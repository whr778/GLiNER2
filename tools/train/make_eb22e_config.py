"""Write base/eb22e.yaml from base/eb22d.yaml.

eb22d plus the from-scratch span-score fix. The new span terms start at the eb21 pair logit
(span_residual_zero_init: additive layers output 0, the inside weight outputs 1, boundary
attention is a pass-through). Rotary changes the endpoint dot product before any of those
terms, so a from-scratch run leaves it off. Loss reduction stays global and the pool stays
per_query.

    uv run tools/train/make_eb22e_config.py
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb22d.yaml", encoding="utf-8"))
head = src["model"]["boundary_head"]
assert head["enable_rotary_endpoints"] is True
assert "span_residual_zero_init" not in head
cfg = dict(src)
cfg["model"] = dict(src["model"], boundary_head=dict(
    head, span_residual_zero_init=True, enable_rotary_endpoints=False,
))
cfg["training"] = dict(src["training"], output_dir="./out/eb22e", experiment_name="eb22e")
note = (
    "# eb22e -- GENERATED by tools/train/make_eb22e_config.py from base/eb22d.yaml; edit that, not this.\n"
    "# eb22d with the from-scratch span score started at the eb21 sum. span_residual_zero_init: the endpoint\n"
    "# difference, span content, and boundary-attention output are 0 at init, and the query-conditioned inside\n"
    "# weight outputs 1. enable_rotary_endpoints off: rotary is not a residual and cannot be zeroed back to that sum.\n"
    "# A Fastino warm start does not use this. Loading a checkpoint overwrites the zeros.\n"
)
Path("tools/train/config/base/eb22e.yaml").write_text(
    note + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True), encoding="utf-8",
)
print("wrote tools/train/config/base/eb22e.yaml")
