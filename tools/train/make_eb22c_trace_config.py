"""Write base/eb22c-trace.yaml: eb22c UNCHANGED, evaluated every 1,000 optimizer steps so the event collapse is seen.

eb22c at the office learned events in epoch 1 and was fully collapsed by epoch 2 (CMNEE and DuEE: event_type,
trigger and argument strict F1 0.0 at every threshold, `Deploy: []` at 0.05; 2026-10-20). A from-scratch overfit
(64 CMNEE docs, task_lr 1e-4) did NOT reproduce it under focal or BCE, so this traces the real run: the trainer now
logs `[losses]` (every per-head loss + pre-clip grad_norm) each logging step and appends each eval to
eval_history.jsonl. Stop the run once the event heads fall; the checkpoints around the drop are kept.

    uv run tools/train/make_eb22c_trace_config.py
    bash tools/train/run_logged.sh tools/train/config/base/eb22c-bce-trace.yaml <num_gpus>   # or eb22c-trace
"""
from pathlib import Path

import yaml

src = yaml.safe_load(open("tools/train/config/base/eb22c.yaml", encoding="utf-8"))
# eb22c-trace: eb22c unchanged (focal), to see the collapse. eb22c-bce-trace: ONE change, boundary_marginal_loss bce
# -- the office run (focal, collapsed by epoch 2) is its control.
for name, head_change in (("eb22c-trace", {}), ("eb22c-bce-trace", {"boundary_marginal_loss": "bce"})):
    cfg = dict(src)
    cfg["model"] = dict(src["model"], boundary_head=dict(src["model"]["boundary_head"], **head_change))
    cfg["training"] = dict(src["training"], output_dir=f"./out/{name}", experiment_name=name, eval_strategy="steps",
                           eval_steps=1000, max_eval_samples=1500, save_total_limit=30)
    head = (f"# {name} -- GENERATED by tools/train/make_eb22c_trace_config.py from base/eb22c.yaml; edit that, not this.\n"
            f"# eb22c except: eval + checkpoint every 1000 steps on 1500 val records, 30 kept; head change {head_change or 'none'}.\n")
    Path(f"tools/train/config/base/{name}.yaml").write_text(head + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
                                                           encoding="utf-8")
    print(f"wrote tools/train/config/base/{name}.yaml | head change {head_change or 'none'}")
